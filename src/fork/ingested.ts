/** All banked ingested assertions. */
export function allIngested(): IngestedAssertion[] {
  return INGESTED_ASSERTIONS;
}

/** Banked assertions about one concept, across sources and aspects. */
export function ingestedFor(concept: string): IngestedAssertion[] {
  const c = concept.toLowerCase();
  return INGESTED_ASSERTIONS.filter((a) => a.concept === c);
}

/** Banked assertions from one chapter of one text. */
export function ingestedFrom(text: string, chapter: string): IngestedAssertion[] {
  return INGESTED_ASSERTIONS.filter((a) => a.citation.text === text && a.citation.chapter === chapter);
}

/**
 * The records for one (concept, aspect) slot that disagree on
 * value — the variant set, if any. Variants coexist by design;
 * this accessor exists so a future consumer must confront the
 * set rather than silently picking one.
 */
export function ingestedVariants(concept: string, aspect: string): IngestedAssertion[] {
  const rows = INGESTED_ASSERTIONS.filter((a) => a.concept === concept.toLowerCase() && a.aspect === aspect);
  const values = new Set(rows.map((a) => a.value));
  return values.size > 1 ? rows : [];
}
