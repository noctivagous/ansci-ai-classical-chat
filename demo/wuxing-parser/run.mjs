#!/usr/bin/env node
/**
 * run.mjs — the standing demonstration of the Wuxing sentence layer.
 *
 * Runs every sentence in sentences.tsv through the real parser
 * (parse -> classify -> join classifications -> controlling-cycle
 * checker -> generate) and regenerates two committed files:
 *
 *   transcript.md — the full per-sentence record (what the parser
 *                   actually did, failures included)
 *   RESULTS.md    — the scoreboard against the corpus expectations,
 *                   with a history table that gains a row whenever
 *                   the scores change
 *
 * Real output only: both files are produced by running the code and
 * are never hand-edited. Run from the repo root:
 *
 *   npm run ansci:demo
 *
 * (which builds first). Or directly, after a build:
 *
 *   node demo/wuxing-parser/run.mjs
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const require = createRequire(import.meta.url);
const B = new URL("../../dist/src/ansci/", import.meta.url).pathname;
const { parse } = require(B + "parse.js");
const { generate } = require(B + "generate.js");
const { checkSentence } = require(B + "check.js");
const { semanticClassifications } = require(B + "sentence.js");
const { lookupClassification } = require(B + "classify.js");
const { buildForkGraph, derive } = require(B + "join.js");

const here = new URL(".", import.meta.url).pathname;
const corpus = readFileSync(here + "sentences.tsv", "utf8")
  .split("\n")
  .filter((l) => l.trim() && !l.startsWith("#"))
  .map((l) => {
    const [lang, text, demonstrates, expectation] = l.split("\t");
    return { lang, text, demonstrates, expectation };
  });

const graph = buildForkGraph();
const today = new Date().toISOString().slice(0, 10);

const t = []; // transcript lines
t.push("# Transcript — the Wuxing sentence layer at work (generated)");
t.push("");
t.push("Generated by `npm run ansci:demo` from `sentences.tsv` in this");
t.push("directory, run through the real sentence layer in `src/ansci/`");
t.push("(parse → classify → join → controlling-cycle checker →");
t.push("generate). Nothing here is hand-written: what the parser did");
t.push("is what stands, failures included. See `RESULTS.md` for the");
t.push("scoreboard and `README.md` for how to read this.");
t.push("");

const rows = []; // scoreboard rows
let nParsed = 0, nClean = 0, nExact = 0, nFlagged = 0, nPass = 0;

for (const c of corpus) {
  t.push(`### ${c.text}`);
  t.push("");
  t.push(`*Demonstrates: ${c.demonstrates}. Expectation: \`${c.expectation}\`.*`);
  t.push("");
  let p = null, parseError = null;
  try { p = parse(c.text, c.lang); } catch (e) { parseError = e.message; }
  if (!p) {
    t.push(`- **parse: FAILED** — ${parseError}`);
    t.push("");
    rows.push({ ...c, status: "FAIL — parse", back: "—" });
    continue;
  }
  nParsed++;
  const nodes = p.meaning.nodes.map((n) =>
    `${n.lemma}:${n.syntacticElement}${n.semanticElement ? "/" + n.semanticElement : ""}(${n.role})`).join("  ");
  t.push(`- classified: ${nodes}`);
  const edges = p.meaning.edges.map((e) => {
    const f = p.meaning.nodes.find((n) => n.id === e.from)?.lemma;
    const to = p.meaning.nodes.find((n) => n.id === e.to)?.lemma;
    return `${f} -${e.relation}-> ${to}`;
  }).join("; ");
  if (edges) t.push(`- relations: ${edges}`);
  for (const sc of semanticClassifications(p)) {
    const entry = lookupClassification(sc.lemma);
    t.push(`- in the net: ${sc.lemma} -> ${sc.semanticElement} (seed node '${sc.seedElementId}')${entry ? ` [${entry.provenance} @${entry.confidence}]` : " [no classify-table entry]"}`);
  }
  if (c.text === "I was furious.") {
    const d = derive(graph, "furious");
    t.push("- derivation sample (furious, through the cycles):");
    for (const concl of d.conclusions.slice(0, 3)) t.push(`  - ${concl.path}  @${concl.confidence.toFixed(2)}`);
  }
  const v = checkSentence(p);
  if (v.length) {
    t.push(`- checker: ${v.map((x) => `FLAGGED ${x.name} (${x.cycle}) — ${x.message}`).join(" | ")}`);
  } else {
    t.push("- checker: no violations");
    nClean++;
  }
  const back = generate(p);
  const exact = back === c.text;
  if (exact) nExact++;
  t.push(`- round-trip: ${back}${exact ? "  *(exact)*" : "  *(canonicalised)*"}`);
  t.push("");

  let pass = false;
  if (c.expectation === "exact") pass = !v.length && exact;
  else if (c.expectation === "canonical") pass = !v.length;
  else if (c.expectation.startsWith("flagged:")) {
    const name = c.expectation.slice("flagged:".length);
    pass = v.some((x) => x.name === name);
    if (pass) nFlagged++;
  }
  if (pass) nPass++;
  rows.push({ ...c, status: pass ? "pass" : "FAIL", back });
}

writeFileSync(here + "transcript.md", t.join("\n"));

// RESULTS.md — current scoreboard + appended history row on change.
const resultsPath = here + "RESULTS.md";
let historyRows = [];
if (existsSync(resultsPath)) {
  const old = readFileSync(resultsPath, "utf8");
  const m = old.match(/## Scoreboard history\n\n\|[^\n]*\n\|[^\n]*\n((?:\|[^\n]*\n?)*)/);
  if (m) historyRows = m[1].trim().split("\n").filter(Boolean);
}
const scoreLine = `${nPass}/${corpus.length} expectations met · ${nParsed} parsed · ${nExact} exact round-trips`;
const newRow = `| ${today} | ${nPass}/${corpus.length} | ${nParsed} | ${nClean} | ${nExact} | ${nFlagged} |`;
if (!historyRows.length || !historyRows[historyRows.length - 1].includes(`| ${nPass}/${corpus.length} | ${nParsed} | ${nClean} | ${nExact} | ${nFlagged} |`)) {
  historyRows.push(newRow);
}

const r = [];
r.push("# Results — the Wuxing sentence layer, scored (generated)");
r.push("");
r.push(`Generated ${today} by \`npm run ansci:demo\`. **${scoreLine}.**`);
r.push("");
r.push("Scored against the expectations in `sentences.tsv`: a sentence");
r.push("passes when the parser does what the corpus says it should —");
r.push("including the two sentences whose expectation is to be");
r.push("*flagged* by the controlling-cycle checker. A FAIL here is a");
r.push("real result and stays in the table until the parser improves.");
r.push("");
r.push("| # | Sentence | Demonstrates | Expectation | Result |");
r.push("| --- | --- | --- | --- | --- |");
rows.forEach((row, i) => {
  r.push(`| ${i + 1} | ${row.text} | ${row.demonstrates} | \`${row.expectation}\` | ${row.status} |`);
});
r.push("");
r.push("## Scoreboard history");
r.push("");
r.push("| Date | Expectations met | Parsed | Checker-clean | Exact round-trips | Expected flags raised |");
r.push("| --- | --- | --- | --- | --- | --- |");
for (const h of historyRows) r.push(h);
r.push("");
writeFileSync(resultsPath, r.join("\n"));

console.log(`demo/wuxing-parser: ${scoreLine}`);
for (const row of rows.filter((x) => x.status !== "pass")) {
  console.log(`  FAIL: ${row.text} (expected ${row.expectation})`);
}
