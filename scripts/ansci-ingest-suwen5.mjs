/**
 * ansci-ingest-suwen5.mjs — the ingestion pipeline's first real
 * run: Suwen ch. 5 (陰陽應象大論） from the Wikisource received
 * text, end to end — acquire → segment → read → propose →
 * review → apply — banking into src/ansci/ingested.ts.
 *
 * The run is deterministic and idempotent: it regenerates the
 * banked store from an empty store, then immediately re-runs
 * the whole pipeline against the freshly banked store and
 * verifies that every proposal is refused as a duplicate
 * (nothing is applied twice). The acquired chapter text is
 * recorded verbatim at data/ingest/suwen-ch5.txt with its
 * source record at data/ingest/suwen-ch5.source.json, so the
 * review stage's quote verification can be re-checked offline.
 *
 * Run via: npm run ansci:ingest
 */
import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const require = createRequire(import.meta.url);
const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const { acquireChapter, runPipeline } = require("../dist/src/ansci/ingest.js");
const { CLASSIFICATIONS } = require("../dist/src/ansci/classify.js");

const SOURCE_URL = "https://zh.wikisource.org/wiki/黃帝內經/素問第二卷";
const RUN_DATE = "2026-11-16";

const sourceBase = {
  text: "黃帝內經 · 素問 (Huángdì Nèijīng, Sùwèn)",
  chapter: "陰陽應象大論第五 (Yīn Yáng Yìng Xiàng Dà Lùn, ch. 5)",
  edition:
    "Wikisource received text (zh.wikisource.org), 黃帝內經/素問第二卷; " +
    "the book's index presents this 素問 as the Jin-dynasty published text",
  sourceUrl: SOURCE_URL,
  retrieved: RUN_DATE,
  sha256: "",
};

async function fetchPage(url) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 30000);
  try {
    const res = await fetch(url, {
      headers: { "User-Agent": "ansci-fork-ingest/0.1 (research prototype; ingestion pipeline run)" },
      signal: ctrl.signal,
    });
    if (!res.ok) throw new Error(`fetch failed: HTTP ${res.status}`);
    return await res.text();
  } finally {
    clearTimeout(timer);
  }
}

const html = await fetchPage(SOURCE_URL);
const provisional = acquireChapter({
  pageHtml: html,
  chapterHeading: "陰陽應象大論第五",
  nextChapterHeading: "陰陽離合論第六",
  source: sourceBase,
});
const sha256 = createHash("sha256").update(provisional.body, "utf8").digest("hex");
const chapter = { source: { ...sourceBase, sha256 }, body: provisional.body };

// Record the acquisition verbatim for offline re-verification.
fs.mkdirSync(path.join(root, "data/ingest"), { recursive: true });
fs.writeFileSync(path.join(root, "data/ingest/suwen-ch5.txt"), chapter.body + "\n", "utf8");
fs.writeFileSync(
  path.join(root, "data/ingest/suwen-ch5.source.json"),
  JSON.stringify(chapter.source, null, 2) + "\n",
  "utf8",
);

// Run 1: against an empty store — this is what gets banked.
const store1 = [];
const run1 = runPipeline(chapter, store1, CLASSIFICATIONS, { date: RUN_DATE, idPrefix: "ing-suwen5" });

// Run 2: against run 1's banked store — idempotency check.
const run2 = runPipeline(chapter, store1, CLASSIFICATIONS, { date: RUN_DATE, idPrefix: "ing-suwen5" });

// Regenerate the banked region of src/ansci/ingested.ts.
const storePath = path.join(root, "src/ansci/ingested.ts");
const storeSrc = fs.readFileSync(storePath, "utf8");
const startMarker = "// === BANKED ASSERTIONS (generated by scripts/ansci-ingest-suwen5.mjs — do not hand-edit) ===";
const endMarker = "// === END BANKED ASSERTIONS ===";
const start = storeSrc.indexOf(startMarker);
const end = storeSrc.indexOf(endMarker);
if (start < 0 || end < 0) throw new Error("ingested.ts: BANKED markers not found");
const generated =
  startMarker +
  "\nexport const INGESTED_ASSERTIONS: IngestedAssertion[] = " +
  JSON.stringify(run1.applied, null, 2) +
  ";\n";
fs.writeFileSync(storePath, storeSrc.slice(0, start) + generated + storeSrc.slice(end), "utf8");

// Rebuild and verify the banked store loads with the run's count.
execFileSync("npm", ["run", "build", "--silent"], { cwd: root, stdio: "inherit" });
delete require.cache[require.resolve("../dist/src/ansci/ingested.js")];
const { INGESTED_ASSERTIONS } = require("../dist/src/ansci/ingested.js");
if (INGESTED_ASSERTIONS.length !== run1.applied.length) {
  throw new Error(`banked store holds ${INGESTED_ASSERTIONS.length}, run applied ${run1.applied.length}`);
}

// Summary for the report.
const byRelation = {};
for (const { outcome } of run1.outcomes) byRelation[outcome.relation] = (byRelation[outcome.relation] ?? 0) + 1;
console.log(JSON.stringify({
  acquiredChars: chapter.body.length,
  sha256,
  passages: run1.passages.length,
  proposals: run1.proposals.length,
  applied: run1.applied.length,
  refused: run1.refused.length,
  byRelation,
  notProposed: run1.notProposed.length,
  rerun: { proposals: run2.proposals.length, applied: run2.applied.length, refused: run2.refused.length,
           allDuplicates: run2.refused.every((r) => r.outcome.relation === "duplicate") },
  bankedInStore: INGESTED_ASSERTIONS.length,
}, null, 2));
