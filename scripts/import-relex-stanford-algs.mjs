#!/usr/bin/env node
/**
 * import-relex-stanford-algs.mjs — vendor the upstream RelEx
 * Stanford-compatibility rule file as a TypeScript string
 * constant for the in-repo engine (src/ansci/linkgrammar-stanford.ts).
 *
 * The engine parses the SAME text RelEx parses (comments and
 * rule layout preserved verbatim); shipping it as a TS module
 * keeps the browser bundle free of a runtime data fetch while
 * the file on disk stays byte-identical to upstream
 * (opencog/relex data/relex-stanford.algs) for auditing.
 *
 * Usage: node scripts/import-relex-stanford-algs.mjs
 * Writes: src/ansci/linkgrammar-stanford-rules.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..");
const src = resolve(repo, "vendor/relex/relex-stanford.algs");
const out = resolve(repo, "src/ansci/linkgrammar-stanford-rules.ts");

const text = readFileSync(src, "utf8").replace(/\r\n/g, "\n");
if (!text.includes("#TemplateActionAlg")) {
  console.error("import-relex-stanford-algs: no rules found in " + src);
  process.exit(1);
}
const literal = JSON.stringify(text);
const header = `/**
 * linkgrammar-stanford-rules.ts — GENERATED, do not edit.
 *
 * Generated by scripts/import-relex-stanford-algs.mjs from
 * vendor/relex/relex-stanford.algs (verbatim upstream text,
 * CRLF normalised to LF), the Stanford-compatibility rule set
 * from opencog/relex (Apache License 2.0, see NOTICE).
 * Regenerate after any vendor update; the engine in
 * src/ansci/linkgrammar-stanford.ts parses this text with the
 * same grammar RelEx itself uses.
 */
`;
writeFileSync(out, header + `\nexport const RELEX_STANFORD_ALGS: string = ${literal};\n`);
console.log(`import-relex-stanford-algs: wrote ${out} (${text.length} chars)`);
