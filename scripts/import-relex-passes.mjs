#!/usr/bin/env node
/**
 * import-relex-passes.mjs — vendor the upstream RelEx tagging
 * and semantic rule files as TypeScript string constants for
 * the in-repo engine (src/ansci/linkgrammar-stanford.ts and
 * src/ansci/linkgrammar-semantic.ts).
 *
 * Same pattern as import-relex-stanford-algs.mjs: the engine
 * parses the SAME text RelEx parses (comments and rule layout
 * preserved); shipping it as a TS module keeps the browser
 * bundle free of a runtime data fetch while the files on disk
 * stay byte-identical to upstream (opencog/relex
 * data/relex-tagging.algs, data/relex-semantic.algs) for
 * auditing.
 *
 * Usage: node scripts/import-relex-passes.mjs
 * Writes: src/ansci/linkgrammar-passes-rules.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..");

function load(name) {
  const src = resolve(repo, "vendor/relex/" + name);
  const text = readFileSync(src, "utf8").replace(/\r\n/g, "\n");
  if (!text.includes("#TemplateActionAlg")) {
    console.error("import-relex-passes: no rules found in " + src);
    process.exit(1);
  }
  return text;
}

const tagging = load("relex-tagging.algs");
const semantic = load("relex-semantic.algs");

const out = resolve(repo, "src/ansci/linkgrammar-passes-rules.ts");
const header = `/**
 * linkgrammar-passes-rules.ts — GENERATED, do not edit.
 *
 * Generated by scripts/import-relex-passes.mjs from
 * vendor/relex/relex-tagging.algs and
 * vendor/relex/relex-semantic.algs (verbatim upstream text,
 * CRLF normalised to LF), the tagging and semantic rule sets
 * from opencog/relex (Apache License 2.0, see NOTICE).
 * Regenerate after any vendor update; the engine in
 * src/ansci/linkgrammar-stanford.ts parses this text with the
 * same grammar RelEx itself uses.
 */
`;
writeFileSync(
  out,
  header +
    `\nexport const RELEX_TAGGING_ALGS: string = ${JSON.stringify(tagging)};\n` +
    `\nexport const RELEX_SEMANTIC_ALGS: string = ${JSON.stringify(semantic)};\n`,
);
console.log(
  `import-relex-passes: wrote ${out} (tagging ${tagging.length} chars, semantic ${semantic.length} chars)`,
);
