// build-dictionary.mjs — generates token-dictionary.txt, the Token
// resolver's frequency dictionary: the top-N words of SymSpell's
// published English frequency dictionary (82,765 words, counts from
// a large web corpus), taken as-is. Regenerate with:
//   node ai-system/lpu/parser/token/build-dictionary.mjs [freqFile] [topN]
// Defaults: freqFile = ~/workspace/ansci-variant-sources/frequency-dictionary-en-82_765.txt
// (fetched from https://raw.githubusercontent.com/wolfgarbe/SymSpell/master/SymSpell/frequency_dictionary_en_82_765.txt),
// topN = 12000. The matcher mechanism is vocabulary-general; N bounds
// the in-memory deletes index, and raising it is a data change.
//
// Why no filtering by the system's lexicon: an earlier version
// intersected with the WordNet extract's lemmas, which silently
// dropped common words the extract does not carry as noun/verb/
// adjective lemmas ("about" — adverb/preposition only) and broke
// segmentation, whose probabilities assume a general dictionary.
// Restricting corrections to words the parser can use is the
// resolver's recognise filter (token-resolve.ts), not the
// dictionary's business.
import * as fs from "node:fs";
import * as path from "node:path";
import * as os from "node:os";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const freqFile = process.argv[2] ?? path.join(os.homedir(), "workspace/ansci-variant-sources/frequency-dictionary-en-82_765.txt");
const topN = Number(process.argv[3] ?? 12000);

const lines = fs.readFileSync(freqFile, "utf-8").replace(/^\uFEFF/, "").split(/\r?\n/);
const kept = [];
for (const line of lines) {
  const m = line.trim().match(/^(\S+)\s+(\d+)$/);
  if (!m) continue;
  kept.push([m[1].toLowerCase(), Number(m[2])]);
  if (kept.length >= topN) break;
}
const out = [
  "# token-dictionary.txt — the Token resolver's frequency dictionary.",
  "# Generated by build-dictionary.mjs (sources and method in that file).",
  `# ${kept.length} words: the top ${topN} of SymSpell's published English frequency dictionary, unfiltered.`,
  "# Format: word<space>corpus-count, one per line, count descending.",
  ...kept.map(([w, c]) => `${w} ${c}`),
].join("\n") + "\n";
fs.writeFileSync(path.join(here, "token-dictionary.txt"), out);
console.log(`wrote ${kept.length} words`);
